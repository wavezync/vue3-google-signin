// Writes CHANGELOG.md and the docs site's changelog page from the commit
// history, with git-cliff (cliff.toml). Arguments go to git-cliff, so
// `pnpm changelog --tag v3.0.0` files unreleased commits under v3.0.0. Set
// GITHUB_TOKEN if GitHub's API rate-limits the contributor lookups.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const run = (command, args) =>
  execFileSync(command, args, {
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  });

const releases = run("git-cliff", process.argv.slice(2));
const files = {
  "CHANGELOG.md": `# Changelog

Every release of vue3-google-signin, newest first. Also on the docs site:
https://vue3-google-signin.wavezync.com/changelog/

${releases}`,

  "docs/src/content/docs/changelog.md": `---
# Generated by \`pnpm changelog\` (scripts/changelog.mjs); don't edit
title: Changelog
description: Every vue3-google-signin release and what changed in it, from breaking changes to bug fixes.
editUrl: false
tableOfContents:
  maxHeadingLevel: 2
---

Every release, newest first. Upgrading from v2? Start with the
[migration guide](/guide/migrating-to-v3/).

<div class="changelog">

${releases}

</div>
`,
};
for (const [path, text] of Object.entries(files)) writeFileSync(path, text);
run("oxfmt", Object.keys(files));
